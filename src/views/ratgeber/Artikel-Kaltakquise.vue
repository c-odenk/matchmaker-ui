      vorliegt. Dafür braucht es einen konkreten Anhaltspunkt, dass das Unternehmen an Ihrem Angebot sachlich
      interessiert ist – ein allgemeiner Bedarf an Personal reicht nicht.
    </p>
    <p>
      Eine offene Stellenanzeige, zu der Ihr Kandidat passt, kann ein solcher Anhaltspunkt sein. Ob sie im
      Einzelfall reicht, ist umstritten. Steht in der Anzeige ausdrücklich, dass Personalvermittler nicht erwünscht
      sind, scheidet eine mutmaßliche Einwilligung aus. Respektieren Sie solche Hinweise – auch aus Gründen der
      Reputation.
    </p>
