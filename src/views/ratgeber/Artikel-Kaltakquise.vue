      abschließend geklärt. Die Funktion ist der E-Mail aber so ähnlich, dass Sie sich nicht auf eine Ausnahme
      verlassen sollten. Eine Kontaktanfrage ohne Verkaufsbotschaft ist unproblematischer. Das Angebot gehört in
      das Gespräch, das entsteht, wenn der Kontakt Interesse zeigt.
    </p>

