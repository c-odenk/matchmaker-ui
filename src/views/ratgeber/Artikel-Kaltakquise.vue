    <h2>Auch ein Kandidatenprofil ist Werbung</h2>
    <p>
      Das UWG versteht Werbung weit: Gemeint ist jede Äußerung, die den Absatz einer Dienstleistung fördern soll.
      Bietet eine Personalvermittlung einem Unternehmen einen Kandidaten an, wirbt sie für ihre
      Vermittlungsleistung. Daran ändert sich nichts, wenn die Nachricht sachlich formuliert ist oder ein
      wirklich passendes Profil enthält.
    </p>
    <p class="merksatz">Die Frage ist deshalb nicht, ob die Ansprache Werbung ist, sondern auf welchem Kanal sie erlaubt ist.</p>

    <h2>E-Mail: nur mit Einwilligung</h2>
    <p>
      Werbung per E-Mail ist nach § 7 Abs. 2 Nr. 2 UWG eine unzumutbare Belästigung, wenn keine vorherige
      ausdrückliche Einwilligung des Empfängers vorliegt. Eine Unterscheidung zwischen Verbrauchern und
      Unternehmen macht das Gesetz hier nicht. Die Einwilligung muss vor der ersten Werbe-E-Mail vorliegen und
      sollte nachweisbar sein.
    </p>
    <p>
      Auch eine E-Mail, die zunächst nur um Erlaubnis für ein Angebot fragt, ordnen Gerichte in der Regel als
      Werbung ein. Dasselbe gilt für Nachrichten über das Kontaktformular einer Unternehmenswebsite.
    </p>
    <h3>Die Ausnahme für bestehende Kunden</h3>
    <p>
      Nach § 7 Abs. 3 UWG dürfen Sie Kunden ohne ausdrückliche Einwilligung per E-Mail ansprechen, wenn Sie die
      Adresse im Zusammenhang mit einem Auftrag erhalten haben, für eigene ähnliche Leistungen werben, der Kunde
      nicht widersprochen hat und Sie bei jeder Nachricht klar auf das Widerspruchsrecht hinweisen. Ein Unternehmen,
      für das Sie schon vermittelt haben, dürfen Sie also unter diesen Bedingungen auch per E-Mail auf einen neuen
      Kandidaten hinweisen.
    </p>
    <h3>Was bei Verstößen droht</h3>
    <p>
      Wettbewerber und bestimmte Verbände können abmahnen und Unterlassung verlangen (§ 8 UWG). Auch der
      Empfänger selbst kann Unterlassung fordern. Die Kosten einer Abmahnung übersteigen schnell den Wert der
      gewonnenen Gesprächschance.
    </p>

    <h2>Telefon: mit mutmaßlicher Einwilligung</h2>
    <p>
