      verlangt werden, der Vertrag muss schriftlich geschlossen werden, und sie darf 2.000 Euro einschließlich
      Umsatzsteuer nicht übersteigen (§ 296 SGB III).
    </p>
    <h3>Vermittlungsgutschein</h3>
    <p>
      Mit einem Aktivierungs- und Vermittlungsgutschein der Agentur für Arbeit oder des Jobcenters zahlt die Behörde
      die Vergütung. Voraussetzung ist eine Zulassung als Träger nach der AZAV. Die Vergütung beträgt 2.000 Euro,
      bei Langzeitarbeitslosen und Menschen mit Behinderungen bis zu 2.500 Euro. Sie wird in zwei Raten gezahlt:
      1.000 Euro nach sechs Wochen Beschäftigung, der Rest nach sechs Monaten (§ 45 Abs. 6 SGB III).
    </p>

