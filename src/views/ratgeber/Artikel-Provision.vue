    <h2>Fälligkeit und Vorstellungsschutz</h2>
    <p>
      Regeln Sie, wann das Honorar fällig wird – mit Vertragsunterschrift oder mit Arbeitsantritt – und mit welchem
      Zahlungsziel. Ebenso wichtig ist der Vorstellungsschutz: Stellt das Unternehmen einen von Ihnen vorgestellten
      Kandidaten innerhalb einer bestimmten Frist ein, etwa innerhalb von zwölf Monaten oder für eine andere Stelle,
      soll das Honorar trotzdem anfallen.
    </p>
    <h3>Provision ohne Vertrag?</h3>
    <p>
      Ohne schriftliche Vereinbarung ist ein Anspruch schwer durchzusetzen. Rechtlich handelt es sich meist um einen
      Maklervertrag (§§ 652 ff. BGB). Er kann zwar auch ohne Unterschrift zustande kommen, Streit über Höhe und
      Fälligkeit ist dann aber kaum zu vermeiden. Schicken Sie Ihre Konditionen deshalb vor der ersten Vorstellung
      und lassen Sie sie bestätigen.
    </p>

    <h2>Regelungen für die Probezeit</h2>
    <p>Scheidet der Kandidat früh wieder aus, sind zwei Regelungen verbreitet:</p>
    <ul>
      <li><strong>Ersatzsuche:</strong> Die Vermittlung sucht ohne weiteres Honorar einen neuen Kandidaten.</li>
      <li><strong>Gestaffelte Rückzahlung:</strong> Ein Teil des Honorars wird erstattet, abhängig davon, wie lange der Kandidat geblieben ist.</li>
    </ul>
    <p>
      Üblich ist ein Zeitraum von drei bis sechs Monaten. Legen Sie fest, wann die Regelung nicht greift – etwa wenn
      das Unternehmen aus betrieblichen Gründen kündigt oder die Stelle wegfällt.
    </p>

    <h2>Sonderfall: Der Arbeitsuchende zahlt</h2>
